/* ==========================================================================
   TGA STORE — PUBLIC API (v1)
   ==========================================================================
   Developer-facing API documented in the site's API Docs (Settings → API
   Docs). Every request needs an apiKey (generated by the user in API Docs)
   and YourID (the user's account ID).

   Actions
     available_countries            -> full country list with stock/price
     country_info[&country_code=]   -> one country (or the full list)
     get_balance                    -> account balance
     getNumber[&country_code=]      -> buy a number (charged to balance)
     getCode[&number=]              -> fetch the login code for a number

   Endpoint: GET/POST /api/v1?action=<action>&apiKey=<key>&YourID=<id>[&...]
   ========================================================================== */

const { getDatabase, readJsonBody, setCors, findUserById } = require("../lib/db");
const { getMaintenance, logEvent } = require("../lib/site");
const {
  getCountryInfo: providerCountryInfo,
  getNumber: providerGetNumber,
  getCode: providerGetCode,
} = require("../lib/tglion");
const { fetchServer2Countries } = require("../lib/server2");
const { sellingPriceInr, sellingPriceUsd } = require("../lib/money");
const {
  BOT_VISIBLE_STATUS,
  telegramIdOf,
  accountIdOf,
  ownerQueries,
} = require("../lib/orders");
const { notifyWebsitePurchase } = require("../lib/notify");

function ok(res, payload, code) {
  return res.status(code || 200).json({ status: "ok", ...payload });
}

function fail(res, message, code) {
  return res.status(code || 400).json({ status: "error", message });
}

function getParam(body, query, name) {
  const v = body[name] !== undefined ? body[name] : query[name];
  if (v === undefined || v === null) return "";
  return String(v).trim();
}

function countryCode(value) {
  const code = String(value || "").trim().toUpperCase();
  return /^[A-Z]{2}$/.test(code) ? code : null;
}

function numberVariants(value) {
  const raw = String(value || "").trim();
  if (!raw) return [];
  const compact = raw.replace(/[^\d+]/g, "");
  const digits = compact.replace(/^\+/, "");
  const withPlus = digits ? `+${digits}` : "";
  return [...new Set([raw, compact, digits, withPlus].filter(Boolean))];
}

module.exports = async function handler(req, res) {
  setCors(res, "GET, POST, OPTIONS");
  if (req.method === "OPTIONS") return res.status(200).end();
  if (req.method !== "GET" && req.method !== "POST") {
    return fail(res, "Method not allowed.", 405);
  }

  const query = req.query || {};
  const body = req.method === "POST" ? readJsonBody(req) : {};

  const action = getParam(body, query, "action").toLowerCase();
  const apiKey = getParam(body, query, "apiKey");
  const yourId = getParam(body, query, "YourID");

  if (!action) return fail(res, "Missing action parameter.");
  if (!apiKey) return fail(res, "Missing apiKey parameter.");
  if (!yourId) return fail(res, "Missing YourID parameter.");

  try {
    const db = await getDatabase();
    const maintenance = await getMaintenance(db);
    if (maintenance.enabled) {
      return fail(res, maintenance.message || "The store is under maintenance. Please try again later.", 503);
    }

    // ---- authenticate ---------------------------------------------------
    const keyDoc = await db.collection("api_keys").findOne({ _id: apiKey });
    if (!keyDoc) return fail(res, "Invalid apiKey. Generate one from your API Docs.", 401);

    let user = await findUserById(db, keyDoc.user_id);
    if (!user && /^\d+$/.test(String(keyDoc.user_id || ""))) {
      user = await db.collection("users").findOne({ _id: Number(keyDoc.user_id) });
    }
    if (!user) return fail(res, "API key owner not found.", 401);

    // YourID must belong to the key owner
    const ownerIds = [
      telegramIdOf(user),
      accountIdOf(user),
      String(user._id),
      user.email ? String(user.email).toLowerCase() : null,
      user.phone || null,
    ].filter((v) => v !== null && v !== undefined).map((v) => String(v));

    const yourIdNorm = String(yourId).replace(/\s+/g, "").toLowerCase();
    const matchesOwner = ownerIds.some(
      (id) => id.replace(/\s+/g, "").toLowerCase() === yourIdNorm
    );
    if (!matchesOwner) {
      return fail(res, "YourID does not match the API key owner.", 403);
    }

    // touch last_used (non-fatal)
    db.collection("api_keys").updateOne(
      { _id: apiKey },
      { $set: { last_used_at: new Date() } }
    ).catch(() => {});

    const telegramId = telegramIdOf(user);
    const accountId = accountIdOf(user) || String(user._id);
    const userIdForOrder = telegramId !== null ? telegramId : accountId;

    // ---- available_countries / country_info ----------------------------
    if (action === "available_countries" || action === "country_info") {
      let countriesList = null;
      try {
        const fetched = await fetchServer2Countries(db);
        countriesList = (fetched && fetched.countries) || null;
      } catch (e) {
        console.error("API countries fetch error:", (e && e.message) || e);
      }

      if (!countriesList || !countriesList.length) {
        return fail(res, "Could not load countries right now. Try again later.", 502);
      }

      const dict = {};
      for (const c of countriesList) {
        const code = String(c.code || "").toUpperCase();
        if (!code) continue;
        dict[code] = {
          name: c.name || code,
          code_Num: String(c.code_Num || ""),
          code,
          qty: Number(c.qty || 0),
          price: String(c.price ?? ""),
        };
      }

      const code = countryCode(getParam(body, query, "country_code"));
      if (action === "country_info" && code) {
        const c = dict[code] || dict[Object.keys(dict).find((k) => k === code)];
        if (!c) return fail(res, "Country is not available right now.", 404);
        return ok(res, c);
      }
      return ok(res, { countries: dict, total: Object.keys(dict).length });
    }

    // ---- get_balance -----------------------------------------------------
    if (action === "get_balance") {
      const balanceUsd = (Number(user.balance || 0) / 100).toFixed(2);
      return ok(res, { balance: `${balanceUsd} USD` });
    }

    // ---- getNumber -------------------------------------------------------
    if (action === "getNumber") {
      const code = countryCode(getParam(body, query, "country_code"));
      if (!code) return fail(res, "country_code is required (e.g. country_code=uz).");

      // 1) stock + price
      let country = null;
      try {
        const fetched = await fetchServer2Countries(db);
        const found = (fetched.countries || []).find(
          (c) => String(c.code || "").toUpperCase() === code
        );
        if (found) country = found;
      } catch (e) {
        console.error("API stock check error:", (e && e.message) || e);
      }
      if (!country) {
        try {
          country = await providerCountryInfo(code);
        } catch (e) {
          return fail(res, "Country is not available right now.", 502);
        }
      }
      if (!country || !Number(country.qty)) {
        return fail(res, `${country?.name || code} is out of stock.`, 409);
      }

      const chargeInr = sellingPriceInr(country.price);
      if (chargeInr === null || chargeInr <= 0) {
        return fail(res, "Could not calculate a selling price for this country.", 502);
      }

      // 2) charge the user (atomic)
      const users = db.collection("users");
      const updated = await users.findOneAndUpdate(
        { _id: user._id, balance: { $gte: chargeInr } },
        { $inc: { balance: -chargeInr } },
        { returnDocument: "after", includeResultMetadata: true }
      );
      const chargedUser = updated?.value || null;
      if (!chargedUser) {
        return fail(res, `Insufficient balance. This account costs $${sellingPriceUsd(country.price).toFixed(2)}.`, 402);
      }

      // 3) buy from the provider
      let purchased = null;
      try {
        purchased = await providerGetNumber(code, country.price);
      } catch (e) {
        // refund
        try {
          await users.updateOne({ _id: user._id }, { $inc: { balance: chargeInr } });
        } catch (refundError) {
          console.error("API refund error:", refundError);
        }
        return fail(res, "Could not purchase a number for this country. Try again.", 502);
      }

      // 4) record the order (bot-compatible shape)
      const order = {
        user_id: userIdForOrder,
        telegram_id: telegramId,
        account_id: accountId,
        country: purchased.name || country.name,
        country_code: code,
        number: purchased.Number,
        otp: null,
        pass: null,
        password: null,
        price: chargeInr,
        provider_price: country.price,
        status: BOT_VISIBLE_STATUS,
        delivery_status: "waiting",
        source: "api",
        created_at: new Date(),
        provider: "tglion",
        provider_hash: null,
      };
      try {
        const inserted = await db.collection("orders").insertOne(order);
        order._id = inserted.insertedId;
      } catch (e) {
        console.error("API order insert error:", (e && e.message) || e);
      }

      await logEvent(db, {
        type: "buy",
        status: "success",
        user_id: telegramId,
        country: order.country,
        country_code: code,
        number: purchased.Number,
        price: chargeInr,
        source: "api",
      });

      try {
        await notifyWebsitePurchase({
          db,
          userId: telegramId,
          accountRef: accountId,
          username: chargedUser.username || "",
          country: order.country,
          countryCode: code,
          number: purchased.Number,
          price: chargeInr,
          balance: Number(chargedUser.balance || 0),
        });
      } catch (e) {
        console.error("API notify error:", (e && e.message) || e);
      }

      const newBalanceUsd = (Number(chargedUser.balance || 0) / 100).toFixed(2);
      return ok(res, {
        name: order.country,
        Number: purchased.Number,
        price: sellingPriceUsd(country.price).toFixed(2),
        new_balance: newBalanceUsd,
        order_id: order._id ? String(order._id) : null,
      });
    }

    // ---- getCode ---------------------------------------------------------
    if (action === "getCode") {
      const number = getParam(body, query, "number");
      if (!number) return fail(res, "number is required (e.g. number=+99800000000).");
      const variants = numberVariants(number);

      const orQueries = ownerQueries(user);
      let order = null;
      for (const uid of orQueries.map((q) => q.user_id)) {
        order = await db.collection("orders").findOne({ user_id: uid, number: { $in: variants } });
        if (order) break;
      }
      if (!order) {
        const found = await db.collection("orders").findOne({ number: { $in: variants } });
        if (found && orQueries.some((q) => String(q.user_id) === String(found.user_id))) order = found;
      }
      if (!order) {
        return fail(res, "No order found for this number.", 404);
      }

      const orderNumber = String(order.number || number).trim();

      let result = null;
      try {
        result = await providerGetCode(orderNumber);
      } catch (e) {
        console.error("API getCode error:", (e && e.message) || e);
      }
      if (!result || !result.code) {
        return fail(res, "OTP is not available yet. Try again in a moment.", 409);
      }

      await db.collection("orders").updateOne(
        { _id: order._id },
        {
          $set: {
            otp: result.code,
            pass: result.pass || "",
            password: result.pass || "",
            status: BOT_VISIBLE_STATUS,
            delivery_status: "completed",
            ...(telegramId !== null ? { user_id: telegramId, telegram_id: telegramId } : {}),
            ...(accountId ? { account_id: accountId } : {}),
            code_at: new Date(),
          },
        }
      );

      await logEvent(db, {
        type: "otp",
        status: "success",
        user_id: telegramId,
        number: result.Number || orderNumber,
        source: "api",
        message: "OTP received via API.",
      });

      return ok(res, {
        Number: result.Number || orderNumber,
        code: result.code,
        pass: result.pass || "",
      });
    }

    return fail(res, "Unknown action. Use available_countries | country_info | get_balance | getNumber | getCode.");
  } catch (e) {
    console.error("TGA API error:", e);
    return fail(res, "Server error. Please try again.", 500);
  }
};
